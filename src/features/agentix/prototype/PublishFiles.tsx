/*
 * Publishing a version as files (D-095). Download is a real browser download of a real file made from
 * this version's content. Saving goes through a connection in Integrations. The states stay honest:
 * preparing, saving, then a confirmed version with its location and time; a failure keeps the last
 * confirmed one on screen, and retrying is offered only where it can't leave a second copy.
 */

export type SaveTarget = Exclude<FileTarget, "download">
const PLACE: Record<SaveTarget, string> = { onedrive: "OneDrive", sharepoint: "SharePoint" }

/* Hands the generated bytes to the browser, which saves them where it saves downloads. */
export function downloadFile(file: GeneratedFile) {
	const url = URL.createObjectURL(new Blob([file.content], { type: `${file.mime};charset=utf-8` }))
	const link = document.createElement("a")
	link.href = url
	link.download = file.name
	document.body.appendChild(link)
	link.click()
	link.remove()
	window.setTimeout(() => URL.revokeObjectURL(url), 1000)
}

export type SaveRoute = { ok: true; connection: Connection; location: string } | { ok: false; reason: string; connect: boolean }

/* Whether this person can save here now, and why not if they can't. The picker's rules, for a write. */
export function saveRoute(org: Pick<OrganizationState, "connections" | "policy">, target: SaveTarget, engagementName: string): SaveRoute {
	const name = PLACE[target]
	const key: ConnectorKey = target
	const mine = org.connections.filter(connection => connection.connector === key && connection.ownerId === VIEWER_ID && connection.state !== "disconnected")
	const connection = mine.find(entry => entry.state === "active") ?? mine[0]
	if (!connection) {
		const other = org.connections.find(entry => entry.connector === key && entry.state !== "disconnected")
		return { ok: false, connect: true, reason: other ? `The ${name} connection here belongs to ${other.ownerName}. Connect your own account to save there.` : `No ${name} account is connected yet.` }
	}
	if (connection.state === "needs_reconnect") return { ok: false, connect: false, reason: `Your ${name} sign-in has expired, so nothing can be written until you reconnect the same account.` }
	if (connection.state !== "active") return { ok: false, connect: false, reason: `Your ${name} connection is not usable right now (${CONNECTION_STATE_LABEL[connection.state].toLowerCase()}).` }
	if (!connection.classes.includes("write")) return { ok: false, connect: false, reason: `Your ${name} connection is read only. Give it write access to save files there.` }
	if (org.policy.integrations.classes !== "read_write") return { ok: false, connect: false, reason: `Your organization's policy allows reads only, so nothing can be written to ${name}.` }
	if (!connection.projects.length) return { ok: false, connect: false, reason: `Your ${name} connection isn't granted to any project yet.` }
	const host = connection.accountLabel.split(" · ").at(-1) ?? name
	return { ok: true, connection, location: `${host}/Agentix/${engagementName}` }
}

const STATUS: Record<FilePublication["status"], { label: string; tone: Tone }> = {
	preparing: { label: "Preparing", tone: "live" }, saving: { label: "Saving", tone: "live" }, saved: { label: "Saved", tone: "positive" },
	failed: { label: "Not saved", tone: "attention" }, uncertain: { label: "Outcome unknown", tone: "attention" }, checking: { label: "Checking", tone: "live" },
}
const placeOf = (publication: FilePublication) => publication.target === "download" ? "this browser" : PLACE[publication.target]
const size = (bytes: number) => bytes < 1024 ? `${bytes} bytes` : `${(bytes / 1024).toFixed(1)} KB`

export function PublishFiles({ state, artifact, version, update }: { state: AgentixState; artifact: Artifact; version: ArtifactVersion; update: (recipe: (state: AgentixState) => AgentixState) => void }) {
	const org = useOrganization()
	const headingId = useId()
	const [asking, setAsking] = useState<SaveTarget | null>(null)
	const cancel = useRef<HTMLButtonElement>(null)
	useEffect(() => { if (asking) cancel.current?.focus() }, [asking])
	const blocked = publishBlock(state, artifact, version)
	const file = fileFor(state, artifact, version)
	const engagement = state.engagements[artifact.engagementId]
	const all = (state.publications ?? []).filter(publication => publication.artifactId === artifact.id)
	const here = all.filter(publication => publication.version === version.version)
	const viewer = org.members.find(member => member.id === VIEWER_ID)
	const routes: Record<SaveTarget, SaveRoute> = { onedrive: saveRoute(org, "onedrive", engagement.name), sharepoint: saveRoute(org, "sharepoint", engagement.name) }
	const inPlace = (target: SaveTarget) => here.find(publication => publication.target === target)
	const download = () => { downloadFile(file); update(current => recordDownload(current, artifact.id, version.version)) }
	const save = (target: SaveTarget) => {
		const route = routes[target]
		if (!route.ok) return
		const destination: FileDestination = { target, connectionId: route.connection.id, location: route.location }
		setAsking(null)
		update(current => requestFileSave(current, artifact.id, version.version, destination))
	}
	const route = asking ? routes[asking] : undefined
	const approval = asking ? connectorFor(asking).operations.find(operation => operation.cls === "write")?.approval : undefined
	const confirmed = all.filter(publication => publication.status === "saved").sort((a, b) => (b.savedAt ?? 0) - (a.savedAt ?? 0))
	const unsettled = here.filter(publication => publication.status !== "saved")
	const problems = (["onedrive", "sharepoint"] as const).flatMap(target => { const value = routes[target]; return value.ok ? [] : [{ target, ...value }] })
	return (
		<section className="aop-files" aria-labelledby={headingId}>
			<div className="aop-subhead"><h3 id={headingId}>Publish as files</h3><span>{file.name} · {size(file.bytes)}</span></div>
			{blocked ? <p className="aop-files-note" role="status">{blocked}</p> : (
				<>
					<div className="aop-actions">
						<DsButton variant="primary" onClick={download}><DownloadSimple size={14} aria-hidden="true" />Download</DsButton>
						{(["onedrive", "sharepoint"] as const).map(target => {
							const existing = inPlace(target)
							return <DsButton key={target} disabled={!routes[target].ok || !!existing} onClick={() => setAsking(target)}>{existing?.status === "saved" ? `Saved to ${PLACE[target]}` : existing && existing.status !== "failed" ? `Saving to ${PLACE[target]}…` : `Save to ${PLACE[target]}`}</DsButton>
						})}
					</div>
					{problems.map(problem => (
						<p key={problem.target} className="aop-files-note">{problem.reason} <TextButton onClick={() => requestSection({ section: "integrations", ...problem.connect ? { connect: problem.target } : {} })}>Open Integrations</TextButton></p>
					))}
					{asking && route?.ok ? (
						<div className="aop-decision-confirm" role="group" aria-label={`Confirm saving to ${PLACE[asking]}`}>
							<p><strong>Save {file.name} to {PLACE[asking]}?</strong> It creates a new file at {route.location}. It never overwrites, renames or shares. {approval ? `${approval}; you're approving as ${viewer?.name ?? "yourself"}.` : ""}</p>
							<div className="aop-actions">
								<DsButton ref={cancel} onClick={() => setAsking(null)}>Cancel</DsButton>
								<DsButton variant="primary" onClick={() => save(asking)}>Save to {PLACE[asking]}</DsButton>
							</div>
						</div>
					) : null}
				</>
			)}
			{unsettled.length || confirmed.length ? (
				<ul className="aop-criteria" aria-label="Files for this result">
					{unsettled.map(publication => {
						const status = STATUS[publication.status]
						const lastHere = confirmed.find(entry => entry.target === publication.target)
						return (
							<li key={publication.id} className="aop-file-row">
								<span className="aop-check-text">
									<span>{publication.fileName}</span>
									<small role={publication.status === "failed" || publication.status === "uncertain" ? "alert" : "status"}>
										{publication.status === "preparing" ? "Building the file and verifying its bytes." : publication.status === "saving" ? `Transferring to ${placeOf(publication)}. It isn't saved until ${placeOf(publication)} confirms it.` : publication.status === "checking" ? `Reading ${placeOf(publication)} back. It only reads.` : publication.failure}
										{publication.status === "failed" || publication.status === "uncertain" ? ` ${lastHere ? `Last confirmed: ${lastHere.fileName}, ${shortTime(lastHere.savedAt ?? 0)}.` : `No version is confirmed in ${placeOf(publication)} yet.`}` : ""}
									</small>
								</span>
								<span className="aop-file-actions">
									<Status label={status.label} tone={status.tone} />
									{publication.status === "failed" && publication.retrySafe ? <DsButton size="sm" onClick={() => update(current => retryFileSave(current, publication.id))}>Try again</DsButton> : null}
									{publication.status === "uncertain" ? <DsButton size="sm" onClick={() => update(current => checkFileSave(current, publication.id))}>Check {placeOf(publication)}</DsButton> : null}
								</span>
							</li>
						)
					})}
					{confirmed.map(publication => (
						<li key={publication.id}>
							<span className="aop-check-text"><span>{publication.fileName}</span><small>{publication.location} · {shortTime(publication.savedAt ?? publication.requestedAt)}{publication.downloads && publication.downloads > 1 ? ` · ${publication.downloads} times` : ""}</small></span>
							<Status label={publication.target === "download" ? "Downloaded" : "Saved"} tone="positive" />
						</li>
					))}
				</ul>
			) : null}
		</section>
	)
}
