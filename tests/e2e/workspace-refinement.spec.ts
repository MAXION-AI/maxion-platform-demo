test("a separate engagement persists its own definition, work and conversation without changing the original", async ({ page }) => {
  await page.goto("/agentix-prototype")
  await page.getByRole("button", { name: "Assign work", exact: true }).click()
  await page.locator("#aop-brief").fill("Review EMEA invoices against the approved purchasing policy")
  await page.getByRole("button", { name: "Create a separate engagement" }).click()
  await page.getByLabel("Engagement name", { exact: true }).fill("EMEA invoice controls")
  await page.getByLabel("Accountable owner").fill("Priya S.")
  await page.getByLabel("Operating scope", { exact: true }).fill("Only EMEA invoices; request explicit price-variance approvals")
  await page.getByRole("button", { name: "All engagements", exact: true }).click()
  await page.locator(".aop-agent-card").filter({ hasText: "EMEA invoice controls" }).click()
  await expect(page.getByLabel("Accountable owner")).toHaveValue("Priya S.")
  await page.getByRole("button", { name: "Run the read-only check" }).click()
  await page.clock.runFor(4000)
  await page.getByRole("button", { name: "Activate engagement" }).click()
  await expect(page.getByRole("heading", { name: "EMEA invoice controls", exact: true })).toBeVisible()
  await expect(page.locator(".aop-now")).toContainText("Ready for incoming work")
  // New work arrives through the engagement's trigger (the demo's incoming event), not a sample-case button.
  await page.getByRole("button", { name: "Controls", exact: true }).click()
  await page.getByRole("button", { name: "Add", exact: true }).click()
  await page.getByRole("button", { name: "Close controls" }).click()
  await page.getByRole("button", { name: "Controls", exact: true }).click()
  await page.getByRole("button", { name: "Skip", exact: true }).click()
  await page.getByRole("button", { name: "Close controls" }).click()
  await page.locator(".aop-work-row").first().click()
  await expect(page.getByRole("button", { name: "Approve $240 variance" })).toBeVisible()
  await page.locator("#aop-composer-input").fill("continue")
  await page.getByRole("button", { name: "Send to the accountable agent" }).click()
  await expect(page.locator(".aop-latest")).toContainText("Not applied")
  await page.reload()
  await expect(page.getByRole("heading", { name: "EMEA invoice controls", exact: true })).toBeVisible()
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem("maxion-agentix-operations-v4")!))
  expect(Object.keys(saved.engagements)).toHaveLength(5)
  const created = Object.values(saved.engagements).find((engagement: { name: string }) => engagement.name === "EMEA invoice controls") as { id: string; scope: string; origin: { kind: string } }
  expect(created.scope).toContain("Only EMEA")
  expect(created.origin.kind).toBe("prompt")
  expect(saved.work.find((item: { reference: string }) => item.reference === "INV-20841").flags.approved).toBeFalsy()
  expect(saved.work.filter((item: { engagementId: string }) => item.engagementId === created.id)).toHaveLength(1)
})

test("the full approval action and the composer remain visible at normal laptop height", async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 720 })
  await page.goto("/agentix-prototype")
  await page.locator(".aop-agent-card").filter({ hasText: "Revenue reconciliation" }).click()
  await page.getByRole("button", { name: "Review details", exact: true }).first().click()
  const approval = await page.getByRole("button", { name: "Approve $240 variance" }).boundingBox()
  const work = await page.locator(".aop-eng-scroll").boundingBox()
  const composer = await page.locator(".aop-eng-dock .ws-composer").boundingBox()
  expect(approval!.y + approval!.height).toBeLessThanOrEqual(work!.y + work!.height)
  expect(composer!.y + composer!.height).toBeLessThanOrEqual(720)
  await page.locator("#aop-composer-input").fill("Keep this case draft")
  await page.getByRole("button", { name: "Details", exact: true }).click()
  await page.keyboard.press("Escape")
  await expect(page.locator("#aop-composer-input")).toHaveValue("Keep this case draft")
  await expect(page.getByRole("button", { name: "Approve $240 variance" })).toBeVisible()
})

