for (const width of [1440, 375]) test(`engagement review fields use the designed layout at ${width}px`, async ({ page }) => {
  await page.setViewportSize({ width, height: 900 })
  await page.goto("/agentix-prototype")
  await page.getByRole("button", { name: "Assign work", exact: true }).click()
  await page.locator(".aop-template").filter({ hasText: "Employee onboarding" }).click()
  await page.getByRole("button", { name: "Create a separate engagement instead" }).click()
  const fields = page.locator(".aop-definition-fields")
  expect(await fields.evaluate(node => getComputedStyle(node).display)).toBe("grid")
  for (const label of ["Engagement name", "Accountable owner", "Operating scope"]) {
    const input = page.getByLabel(label, { exact: true })
    const bounds = await input.boundingBox()
    expect(bounds!.width).toBeGreaterThan(width === 375 ? 240 : 280)
    expect(await input.evaluate(node => getComputedStyle(node).borderTopStyle)).toBe("solid")
    expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(width)
  }
  const name = await page.getByLabel("Engagement name", { exact: true }).boundingBox()
  const owner = await page.getByLabel("Accountable owner").boundingBox()
  if (width > 900) expect(owner!.x).toBeGreaterThanOrEqual(name!.x + name!.width)
  else expect(owner!.y).toBeGreaterThanOrEqual(name!.y + name!.height)
})

test("Discovery shows current work before supporting metrics on mobile and keeps operation status out of context", async ({ page }) => {
  await page.setViewportSize({ width: 375, height: 812 })
  await page.goto("/discovery-prototype")
  await page.getByRole("button", { name: "Resume ServiceNow financial-control integration, Working autonomously" }).click()
  await page.getByRole("button", { name: "Thread", exact: true }).click()
  await expect(page.locator(".thread-inspector")).not.toContainText("Current operation")
  await expect(page.getByRole("textbox", { name: "Message MAX" })).toBeVisible()
  await page.getByRole("button", { name: "Autonomy", exact: true }).click()
  await page.clock.runFor(500)
  const trace = await page.getByRole("button", { name: /Inspect the current work trace/ }).boundingBox()
  const metrics = await page.getByRole("region", { name: "Work handled by MAX" }).boundingBox()
  expect(trace!.y + trace!.height).toBeLessThanOrEqual(812)
  expect(trace!.y).toBeLessThan(metrics!.y)
  const progress = await page.locator(".autonomy-progress-summary").evaluate(node => ({ width: node.clientWidth, scroll: node.scrollWidth }))
  expect(progress.scroll).toBeLessThanOrEqual(progress.width)
  // Long rotating activity text must fit its own card, not merely a clipped page.
  for (const width of [375, 1280]) {
    await page.setViewportSize({ width, height: 812 })
    const line = page.locator(".dsc-now-line").first()
    await line.locator(".dsc-now-text").evaluate(node => {
      node.textContent = "Comparing system ownership against Change and incident management evidence from ServiceNow and the approved finance operating context"
    })
    const bounds = await line.evaluate(node => {
      const text = node.querySelector(".dsc-now-text")!
      return { lineRight: node.getBoundingClientRect().right, textRight: text.getBoundingClientRect().right, cardRight: node.closest(".autonomy-current")!.getBoundingClientRect().right, display: getComputedStyle(node).display, fontSize: parseFloat(getComputedStyle(text).fontSize) }
    })
    expect(bounds.display).toBe("flex")
    expect(bounds.fontSize).toBeGreaterThanOrEqual(12)
    expect(bounds.textRight).toBeLessThanOrEqual(bounds.lineRight)
    expect(bounds.lineRight).toBeLessThanOrEqual(bounds.cardRight)
  }
})

test("a Discovery status question or negation never becomes a sponsor-send instruction", async ({ page }) => {
  await page.goto("/discovery-prototype")
  await page.getByRole("button", { name: "Resume ServiceNow financial-control integration, Working autonomously" }).click()
  await page.getByRole("button", { name: "Thread", exact: true }).click()
  const composer = page.getByRole("textbox", { name: "Message MAX" })
  for (const text of ["What is the status?", "Do not send the sponsor a status update", "What is the invitation status?"]) {
    await composer.fill(text)
    await composer.press("Enter")
    await page.clock.runFor(250)
    await expect(page.locator(".max-message").last()).toContainText("No sponsor update was sent.")
    await expect(page.locator(".max-message").last()).not.toContainText("Sent and verified")
  }
  await composer.fill("Send the sponsor a status update")
  await composer.press("Enter")
  await page.clock.runFor(250)
  await expect(page.locator(".max-message").last()).toContainText("Status update sent to the approved sponsor")
  await expect(page.locator(".max-message").last()).not.toContainText("Demo")
})
