test("dark mode, keyboard, focus containment and value disclosures remain usable", async ({ page }) => {
  await enter(page)
  await page.emulateMedia({ colorScheme: "dark", reducedMotion: "reduce" })
  await open(page, "Invoice operations agent")
  await page.getByText("How this is calculated", { exact: true }).click()
  await expect(page.getByRole("region", { name: "Outcome performance" })).toContainText("no labor savings or ROI is claimed")
  await page.getByRole("button", { name: "Message agent" }).click()
  await send(page, "Why this team?")
  await expect(page.getByRole("log")).toContainText("single ERP write")
  await page.keyboard.press("ControlOrMeta+k")
  await expect(page.getByRole("dialog", { name: "MAXION command menu" })).toHaveCount(0)
  await page.keyboard.press("Tab")
  expect(await page.evaluate(() => !!document.activeElement?.closest("dialog"))).toBe(true)
  await page.clock.resume()
  const scan = await new AxeBuilder({ page }).include(".aop-drawer").analyze()
  expect(scan.violations.filter(v => v.impact === "serious" || v.impact === "critical")).toEqual([])
  await page.keyboard.press("Escape")
  await page.keyboard.press("ControlOrMeta+k")
  await expect(page.getByRole("dialog", { name: "MAXION command menu" })).toBeVisible()
})

