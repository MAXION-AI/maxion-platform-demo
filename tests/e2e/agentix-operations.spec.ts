import AxeBuilder from "@axe-core/playwright"
import { expect, test, type Page } from "@playwright/test"

async function enter(page: Page) {
  await page.emulateMedia({ reducedMotion: "reduce" })
  await page.clock.install({ time: new Date("2026-09-11T08:00:00Z") })
  await page.clock.pauseAt(new Date("2026-09-11T09:00:00Z"))
  await page.goto("/agentix-prototype")
  await expect(page.getByRole("heading", { name: /decisions\. Everything else is moving\./ })).toBeVisible()
}
const ticks = (page: Page, n: number) => page.clock.runFor(n * 4000)
async function open(page: Page, agent: string) {
  if (agent === "Employee onboarding agent") {
    await page.getByRole("button", { name: "New agent", exact: true }).click()
    await page.getByLabel("Describe the responsibility").fill("Coordinate employee onboarding")
    await page.getByRole("button", { name: "Prepare agent" }).click()
    return
  }
  await page.locator(".aop-agent-line").filter({ hasText: agent }).click()
}
const caseRow = (page: Page, id: string) => page.locator(".aop-run-row").filter({ hasText: id })
const close = (page: Page) => page.getByRole("button", { name: "Close details" }).click()
async function send(page: Page, text: string) {
  await page.locator("#aop-message").fill(text)
  await page.getByRole("button", { name: "Send instruction" }).click()
}
async function repairMapping(page: Page) {
  await page.getByRole("button", { name: "Confirm mapping" }).click()
  await page.getByLabel("London analyst → approved access package").selectOption("london-standard")
  await page.getByRole("button", { name: "Recheck readiness" }).click()
  await expect(page.getByText("Validating mapping, operation coverage and read-back…")).toBeVisible()
  await ticks(page, 1)
}

test("operations portfolio keeps decisions, work, activity, connections and steering in context", async ({ page }) => {
  await enter(page)
  await expect(page.getByRole("navigation", { name: "Agentix views" }).getByRole("button")).toHaveCount(5)
  await expect(page.locator(".aop-agent-line")).toHaveCount(3)
  await expect(page.getByRole("textbox", { name: "Steer Agentix" })).toBeVisible()
  await expect(page.locator("#aop-message")).toHaveCount(0)
  const views = page.getByRole("navigation", { name: "Agentix views" })
  await views.getByRole("button", { name: "Work", exact: true }).click()
  await expect(page.getByRole("heading", { name: "Work" })).toBeVisible()
  await views.getByRole("button", { name: /Approvals/ }).click()
  await expect(page.getByRole("button", { name: "Review" }).first()).toBeVisible()
  await views.getByRole("button", { name: "Today", exact: true }).click()
  await open(page, "Invoice operations agent")
  await expect(page.locator(".aop-run-row")).toHaveCount(5)
  await expect(caseRow(page, "INV-20844")).toContainText("Verifying")
  await ticks(page, 10)
  await expect(caseRow(page, "INV-20841")).toContainText("Needs approval")
  await page.getByRole("button", { name: /^History/ }).click()
  await expect(caseRow(page, "INV-20842")).toContainText("Verified")
  await expect(page.getByRole("button", { name: "Pause intake" })).toBeEnabled()
  await expect(page.getByRole("region", { name: "Outcome performance" })).toContainText("5 / 7")
})

test("conversation is a scoped secondary drawer and cannot bypass a case approval", async ({ page }) => {
  await enter(page); await open(page, "Invoice operations agent")
  await caseRow(page, "INV-20841").click()
  await page.getByRole("button", { name: "Message about this case" }).click()
  await expect(page.getByRole("dialog", { name: "Agent conversation" })).toContainText("This case only · INV-20841")
  await send(page, "continue")
  await expect(page.getByRole("log")).toContainText("cannot bypass")
  await close(page)
  await caseRow(page, "INV-20841").click()
  await page.getByRole("button", { name: "Approve $240 variance" }).click()
  await expect(page.getByRole("dialog")).toContainText("Queued")
  await ticks(page, 7)
  await expect(page.getByRole("dialog")).toContainText("Change applied · awaiting source read-back")
  await ticks(page, 3)
  await expect(page.getByRole("dialog")).toContainText("Completed for INV-20841 only")
  await close(page)
  await expect(page.getByRole("button", { name: "Pause intake" })).toBeVisible()
})

test("pause intake leaves admitted work running; steering persists without a conversation", async ({ page }) => {
  await enter(page); await open(page, "Invoice operations agent")
  await page.getByRole("button", { name: "Pause intake" }).click()
  await ticks(page, 10)
  await expect(caseRow(page, "INV-20845")).toContainText("Queued")
  await page.getByRole("button", { name: "Message agent" }).click()
  await page.locator("#aop-message").fill("Keep this unfinished direction")
  await close(page)
  await page.reload()
  await expect(page.getByRole("button", { name: "Resume intake" })).toBeVisible()
  await page.getByRole("button", { name: "Message agent" }).click()
  await expect(page.locator("#aop-message")).toHaveValue("Keep this unfinished direction")
  await send(page, "Resume intake")
  await close(page)
  await ticks(page, 1)
  await expect(caseRow(page, "INV-20845")).toContainText("Working")
})

test("configuration repair and explicit unsupported-scope repair precede deployment", async ({ page }) => {
  await enter(page); await open(page, "Employee onboarding agent")
  const deploy = page.getByRole("button", { name: "Deploy agent in demo" })
  await expect(deploy).toBeDisabled()
  await page.getByText("Operation checks", { exact: true }).click()
  await page.getByRole("button", { name: "What if payroll must be fully automated?" }).click()
  await expect(page.getByText("Automatic payroll provisioning isn’t supported.")).toBeVisible()
  await page.getByRole("button", { name: "Request this capability from MAXION" }).click()
  await expect(deploy).toBeDisabled()
  await expect(page.getByRole("button", { name: /Demo request AGX-104/ })).toBeDisabled()
  await page.getByRole("button", { name: "Keep payroll with its owner" }).click()
  await repairMapping(page)
  await expect(deploy).toBeEnabled()
  await deploy.click()
  await expect(page.getByRole("region", { name: "Agent operating status" })).toContainText("Watching incoming events")
  await ticks(page, 5)
  await caseRow(page, "JOIN-306").click()
  await expect(page.getByRole("region", { name: "Human fulfillment" })).toBeVisible()
  await page.getByRole("button", { name: "Attach owner confirmation" }).click()
  await expect(page.getByRole("alert")).toContainText("Enter the owner’s fulfillment reference")
  await page.getByLabel("Fulfillment reference").fill("PAYROLL-306/OWNER-2")
  await page.getByRole("button", { name: "Attach owner confirmation" }).click()
  await ticks(page, 5)
  await expect(page.getByRole("dialog")).toContainText("Completed for JOIN-306 only")
})

